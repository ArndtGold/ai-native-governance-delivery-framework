import fs from 'node:fs';
import crypto from 'node:crypto';
import assert from 'node:assert/strict';
import {withStdioClient} from '/Users/arndtgold/Documents/GitHub/ai-native-governance-delivery-framework/packages/mcp-server/test/helpers.js';
import {inspectMcpServerPackage} from '/Users/arndtgold/Documents/GitHub/ai-native-governance-delivery-framework/packages/cli/lib/mcp-lifecycle/package.js';
import {treeBytes} from '/Users/arndtgold/Documents/GitHub/ai-native-governance-delivery-framework/packages/core/test/control-cockpit-fixtures.js';
const root='/Users/arndtgold/Documents/GitHub/ai-native-governance-delivery-framework';
const run='agdf-cockpit-mcp-app-20261005-01';
const p=JSON.parse(fs.readFileSync(`${root}/dist/local/codex-cockpit/preparation.json`));
const owned=inspectMcpServerPackage({dataRoot:`${root}/dist/local/codex-cockpit/runtime`,expectedVersion:p.version});
assert.equal(owned.status,'matched');
assert.equal(owned.digest,p.server_digest); assert.equal(owned.dispatcherDigest,p.dispatcher_digest);assert.equal(owned.sdkDigest,p.sdk_digest);
const before=treeBytes(root), observed=[];
for(const modern of [false,true]) await withStdioClient({modern,command:p.node,args:[p.entrypoint,'--surface','codex','--cockpit-dir',root]},async client=>{
 const resource=await client.readResource({uri:p.ui.uri});
 const html=resource.contents[0].text, digest='sha256:'+crypto.createHash('sha256').update(html).digest('hex');
 assert.equal(digest,p.ui.digest); assert.equal(Buffer.byteLength(html),p.ui.bytes);
 const opened=await client.callTool({name:'agdf_cockpit',arguments:{run_id:run}});
 assert.equal(opened._meta.agdf_cockpit.initial_run_id,run);
 const session_id=opened._meta.agdf_cockpit.session_id;
 const call=args=>client.callTool({name:'agdf_cockpit_read',arguments:{session_id,...args}});
 const snapshot=(await call({operation:'snapshot'})).structuredContent;
 assert.ok(['available','partial'].includes(snapshot.state), 'inventory must be readable; known restricted historical rows may make it partial');
 const detail=(await call({operation:'run',snapshot_id:snapshot.snapshot_id,run_id:run})).structuredContent;
 assert.equal(detail.state,'available'); assert.equal(detail.data.run_id,run);
 observed.push({protocol:modern?'2026-07-28':'2025-11-25',ui_digest:digest,ui_bytes:Buffer.byteLength(html),inventory_state:snapshot.state,run_state:detail.state,run_id:detail.data.run_id,revision_id:detail.data.revision_id,assessment:detail.data.evaluation.control_assessment});
 await call({operation:'close'});
});
assert.deepEqual(treeBytes(root),before);
console.log(JSON.stringify({status:'pass',observed_at:new Date().toISOString(),evidence_class:'fresh_registered_entrypoint_stdio_not_native_host',owned_runtime_status:owned.status,control_unchanged:true,observations:observed}));
