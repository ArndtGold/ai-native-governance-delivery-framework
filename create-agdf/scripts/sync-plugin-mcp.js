import { chmodSync, lstatSync, mkdirSync, readFileSync, readdirSync, rmSync, statSync, writeFileSync } from "node:fs";
import { dirname, join, relative, resolve } from "node:path";
import { fileURLToPath } from "node:url";
import { CODEX_PLUGIN_MCP_FILE, renderCodexPluginMcpConfig } from "../lib/runtime/plugin-provenance.js";

const scriptsRoot = dirname(fileURLToPath(import.meta.url));
const repoRoot = resolve(scriptsRoot, "..", "..");
const serverSourceRoot = join(repoRoot, "agdf-mcp-server");
const SERVER_ENTRIES = Object.freeze(["package.json", "bin", "src", "README.md", "NOTICE"]);

// The Claude MCP registration is part of the runtime plugin, so `claude plugin uninstall` removes it.
// ${CLAUDE_PLUGIN_ROOT} and ${CLAUDE_PLUGIN_DATA} are expanded by Claude Code; the launcher reads the
// data root from the environment Claude Code passes to plugin MCP servers.
export function claudePluginMcpConfig() {
  return {
    mcpServers: {
      agdf: {
        type: "stdio",
        command: "node",
        args: ["${CLAUDE_PLUGIN_ROOT}/mcp/agdf-mcp-launch.js"],
      },
    },
  };
}

const LAUNCHER = `#!/usr/bin/env node

// Generated by create-agdf/scripts/sync-plugin-mcp.js; do not edit.
import { fileURLToPath } from "node:url";
import { launchClaudePluginMcpServer } from "../runtime/create-agdf/lib/mcp-lifecycle/plugin-runtime.js";

await launchClaudePluginMcpServer({ pluginRoot: fileURLToPath(new URL("../", import.meta.url)) });
`;

function copyText(source, destination, expected, root) {
  const stats = statSync(source);
  if (stats.isDirectory()) {
    for (const entry of readdirSync(source)) copyText(join(source, entry), join(destination, entry), expected, root);
    return;
  }
  mkdirSync(dirname(destination), { recursive: true });
  writeFileSync(destination, readFileSync(source, "utf8").replaceAll("\r\n", "\n"), "utf8");
  chmodSync(destination, stats.mode);
  expected.add(relative(root, destination).replaceAll("\\", "/"));
}

export function syncClaudePluginMcp({ pluginRoot } = {}) {
  if (!pluginRoot || resolve(pluginRoot) !== pluginRoot) throw new Error("Claude MCP sync requires an absolute pluginRoot.");
  const mcpRoot = join(pluginRoot, "mcp");
  mkdirSync(mcpRoot, { recursive: true });
  const expected = new Set(["claude.mcp.json", "codex.mcp.json", "agdf-mcp-launch.js"]);
  writeFileSync(join(mcpRoot, "claude.mcp.json"), `${JSON.stringify(claudePluginMcpConfig(), null, 2)}\n`, "utf8");
  writeFileSync(join(mcpRoot, "agdf-mcp-launch.js"), LAUNCHER, "utf8");
  // Template only: the installer writes the absolute marketplace paths Codex requires.
  writeFileSync(join(pluginRoot, CODEX_PLUGIN_MCP_FILE), renderCodexPluginMcpConfig(), "utf8");
  for (const entry of SERVER_ENTRIES) {
    copyText(join(serverSourceRoot, entry), join(mcpRoot, "server", entry), expected, mcpRoot);
  }
  const pruneRoot = (directory) => {
    for (const name of readdirSync(directory)) {
      const path = join(directory, name);
      const stats = lstatSync(path);
      if (stats.isDirectory() && !stats.isSymbolicLink()) {
        pruneRoot(path);
        if (readdirSync(path).length === 0) rmSync(path, { recursive: true, force: true });
      } else if (!expected.has(relative(mcpRoot, path).replaceAll("\\", "/"))) {
        rmSync(path, { force: true });
      }
    }
  };
  pruneRoot(mcpRoot);
  return [...expected].sort().map((path) => `mcp/${path}`);
}
