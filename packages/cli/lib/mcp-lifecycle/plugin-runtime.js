// Plugin-local AGDF MCP runtime shared by the hosts whose runtime plugin declares the server itself:
// Claude Code passes ${CLAUDE_PLUGIN_DATA}, which it deletes on uninstall; Codex receives an absolute
// AGDF-owned data root from the installer-written declaration. The plugin ships the server and
// dispatcher; only the pinned MCP SDK is installed from npm, once.
const SDK_PACKAGE_SPEC = "@modelcontextprotocol/server@2.0.0";
// Without the override the SDK is installed with `npm ci` from the lock the plugin ships and must match
// the shipped digest; the override deliberately restores the unverified install and is recorded.
export const SDK_BUNDLE = Object.freeze({ manifest: "package.json", lock: "package-lock.json", expected: "expected-sdk.json" });
export const SDK_OVERRIDE_ENV = "AGDF_MCP_ALLOW_UNVERIFIED_SDK";
export const SDK_VERIFICATION = Object.freeze({ verified: "verified", override: "unverified_override" });

function readJson(path) {
  try { return JSON.parse(readFileSync(path, "utf8")); } catch { return null; }
}

function ownedRoot(root) {
  return readJson(join(root, mcpPackageConstants.marker))?.owner === mcpPackageConstants.owner;
}

export function pluginMcpVersion(pluginRoot) {
  const version = readJson(join(pluginRoot, "runtime", "runtime-manifest.json"))?.version;
  if (typeof version !== "string" || !version) throw new Error("AGDF_MCP_PLUGIN_RUNTIME_INVALID");
  return version;
}

function copyPluginPackages({ pluginRoot, stage, version }) {
  const serverSource = join(pluginRoot, "mcp", "server");
  const runtimePackage = join(pluginRoot, "runtime", "create-agdf");
  if (!existsSync(join(serverSource, "package.json")) || !existsSync(runtimePackage)) {
    throw new Error("AGDF_MCP_PLUGIN_RUNTIME_INVALID");
  }
  cpSync(serverSource, join(stage, "node_modules", "@agdf", "mcp-server"), { recursive: true });
  const dispatcherRoot = join(stage, "node_modules", "create-agdf");
  for (const entry of MCP_DISPATCHER_RUNTIME_ENTRIES.filter((item) => item !== "package.json")) {
    cpSync(join(runtimePackage, entry), join(dispatcherRoot, entry), { recursive: true });
  }
  writeFileSync(join(dispatcherRoot, "package.json"), `${JSON.stringify({
    name: "create-agdf",
    version,
    private: true,
    type: "module",
    exports: { "./mcp-dispatch-runtime": "./lib/mcp-dispatch-runtime.js" },
    imports: { "#agdf-core": "./runtime/core/lib/index.js", "#agdf-core/*": "./runtime/core/lib/*" },
  }, null, 2)}\n`, "utf8");
}

// The locked SDK bundle the plugin ships under mcp/sdk/ (generated by scripts/sync-plugin-mcp.js).
export function readPluginSdkBundle(pluginRoot) {
  const sdkRoot = join(pluginRoot, "mcp", "sdk");
  const expected = readJson(join(sdkRoot, SDK_BUNDLE.expected));
  if (expected?.schema_version !== 1 || typeof expected.sdk_digest !== "string" || !Array.isArray(expected.packages)
      || !existsSync(join(sdkRoot, SDK_BUNDLE.manifest)) || !existsSync(join(sdkRoot, SDK_BUNDLE.lock))) {
    throw new Error("AGDF_MCP_PLUGIN_RUNTIME_INVALID");
  }
  return Object.freeze({ sdkRoot, expected });
}

export function sdkOverrideActive(env = process.env) {
  return env?.[SDK_OVERRIDE_ENV] === "1";
}

export function ensurePluginMcpRuntime({
  pluginRoot,
  dataRoot,
  execPath = process.execPath,
  exec = execFileSync,
  npmOptions = {},
  now = Date.now(),
  env = process.env,
  publicationDeadline = performance.now() + CONCURRENT_PUBLICATION_WAIT_MS,
} = {}) {
  if (!pluginRoot || !dataRoot) throw new Error("AGDF_MCP_PLUGIN_DATA_MISSING");
  const version = pluginMcpVersion(pluginRoot);
  const { sdkRoot, expected } = readPluginSdkBundle(pluginRoot);
  const override = sdkOverrideActive(env);
  mkdirSync(resolve(dataRoot), { recursive: true });
  if (lstatSync(resolve(dataRoot)).isSymbolicLink()) throw Error('AGDF_MCP_RUNTIME_UNOWNED');
  const mcpDataRoot = join(realpathSync(resolve(dataRoot)), "mcp");
  if (existsSync(mcpDataRoot) && lstatSync(mcpDataRoot).isSymbolicLink()) throw Error('AGDF_MCP_RUNTIME_UNOWNED');
  mkdirSync(mcpDataRoot, { recursive: true });
  const sourceServerDigest = digestDirectory(join(pluginRoot, "mcp", "server"));
  const sourceDispatcherDigest = digestPluginMcpDispatcherSource(join(pluginRoot, "runtime", "create-agdf"), version);
  // Keep old, foreign and unclaimed roots intact. Same-version updates publish
  // another content-addressed package, rather than moving executing files away.
  const key = createHash('sha256').update(JSON.stringify({ version, server: sourceServerDigest,
    dispatcher: sourceDispatcherDigest, sdk: expected.sdk_digest, verification: override ? 'unverified_override' : 'verified' })).digest('hex');
  const publicationRoot = join(mcpDataRoot, 'generations', key);
  for (const path of [join(mcpDataRoot, 'generations'), publicationRoot]) {
    if (existsSync(path) && lstatSync(path).isSymbolicLink()) throw Error('AGDF_MCP_RUNTIME_UNOWNED');
    mkdirSync(path, { recursive: true });
  }
  const published = runtime => Object.freeze({ ...runtime, publication_id: key, publisher_root: mcpDataRoot, immutable: true });
  // Without the override only a runtime holding exactly the shipped SDK tree is reused; one installed
  // under the override, or before the plugin shipped an expected digest, is re-verified by replacement.
  const usable = (runtime) => runtime.status === "matched"
    && runtime.digest === sourceServerDigest
    && runtime.dispatcherDigest === sourceDispatcherDigest
    && (override || (runtime.sdkDigest === expected.sdk_digest && runtime.sdkVerification !== SDK_VERIFICATION.override));
  const replacementDeadline = publicationDeadline;
  // After a plugin update several launchers replace the same runtime at once (Claude's version probe and
  // respawn, every plugin server, reconnecting sessions); states they cause each other are retried briefly.
  for (let attempt = 1; ; attempt += 1) {
    const current = inspectMcpServerPackage({ dataRoot: publicationRoot, expectedVersion: version });
    if (usable(current)) {
      if (performance.now() >= publicationDeadline) throw Error('AGDF_MCP_PUBLICATION_DEADLINE_EXCEEDED');
      return published({ ...current, changed: false });
    }
    try {
      if (current.status !== 'absent') throw Error(ownedRoot(current.root) ? 'AGDF_MCP_IMMUTABLE_RUNTIME_MISMATCH' : 'AGDF_MCP_RUNTIME_UNOWNED');
      const prepared = prepareMcpServerPackage({
        dataRoot: publicationRoot,
        immutable: true,
        expectedVersion: version,
        publicationDeadline,
        execPath,
        exec,
        npmOptions,
        expectedSdk: override ? null : expected,
        sdkVerification: override ? SDK_VERIFICATION.override : SDK_VERIFICATION.verified,
        acquire({ stage, install, installLocked }) {
          if (override) {
            install([SDK_PACKAGE_SPEC]);
          } else {
            cpSync(join(sdkRoot, SDK_BUNDLE.manifest), join(stage, "package.json"));
            cpSync(join(sdkRoot, SDK_BUNDLE.lock), join(stage, "package-lock.json"));
            installLocked();
          }
          copyPluginPackages({ pluginRoot, stage, version });
        },
      });
      prepared.commit();
      return published(prepared);
    } catch (error) {
      if (performance.now() >= publicationDeadline) throw Error('AGDF_MCP_PUBLICATION_DEADLINE_EXCEEDED');
      // A concurrent launcher may have installed the same runtime first.
      const settled = inspectMcpServerPackage({ dataRoot: publicationRoot, expectedVersion: version });
      if (usable(settled)) return published({ ...settled, changed: false });
      const publicationLocked = error?.message === 'AGDF_RUN_WRITE_LOCKED';
      if (publicationLocked && error.lock_owner_status !== 'live') throw error;
      if (!concurrentReplacementError(error)
          || (publicationLocked ? performance.now() >= replacementDeadline : attempt >= CONCURRENT_REPLACEMENT_ATTEMPTS)) throw error;
      sleepSync(publicationLocked
        ? Math.min(CONCURRENT_REPLACEMENT_DELAY_MS, Math.max(0, replacementDeadline - performance.now()))
        : CONCURRENT_REPLACEMENT_DELAY_MS * attempt);
    }
  }
}

const CONCURRENT_REPLACEMENT_ATTEMPTS = 6;
const CONCURRENT_REPLACEMENT_DELAY_MS = 150;
// SDK acquisition and copying can exceed the old 2.25-second retry window on
// Windows. Wait for the publication owner without taking or removing its lock.
const CONCURRENT_PUBLICATION_WAIT_MS = 30_000;

// Only states another launcher can cause: a runtime moved away mid-inspection or a lost stage rename.
// npm, SDK and verification failures are never retried.
function concurrentReplacementError(error) {
  return ['AGDF_MCP_RUNTIME_UNOWNED', 'AGDF_RUN_WRITE_LOCKED'].includes(error?.message) || ["EPERM", "EEXIST", "ENOTEMPTY", "EBUSY", "ENOENT"].includes(error?.code);
}

function sleepSync(milliseconds) {
  Atomics.wait(new Int32Array(new SharedArrayBuffer(4)), 0, 0, milliseconds);
}

// Claude Code passes ${CLAUDE_PLUGIN_DATA} in the environment and needs no arguments; its cockpit entry
// adds the project root Claude substitutes for ${CLAUDE_PROJECT_DIR}. Codex and Copilot declarations
// pass the surface and an absolute data root after host variable expansion.
export function parseLauncherArguments(argv, env = {}) {
  const args = [...argv];
  const prepareOnly = args.at(-1) === "--prepare";
  if (prepareOnly) args.pop();
  if (args.length === 0) return { surface: "claude", dataRoot: env.CLAUDE_PLUGIN_DATA, prepareOnly };
  if (args.length === 2 && args[0] === "--cockpit-dir" && typeof args[1] === "string" && isAbsolute(args[1]) && !args[1].includes("${")) {
    return { surface: "claude", dataRoot: env.CLAUDE_PLUGIN_DATA, cockpitDir: args[1], prepareOnly };
  }
  if (args.length === 4 && args[0] === "--surface" && ["codex", "copilot"].includes(args[1]) && args[2] === "--data"
      && typeof args[3] === "string" && isAbsolute(args[3])) {
    return { surface: args[1], dataRoot: args[3], prepareOnly };
  }
  return null;
}

// One stderr line per failure: stable code, cause and one recovery action. Plugin skills and hooks do
// not depend on this launcher and keep working while the MCP server is refused.
const LAUNCHER_FAILURES = Object.freeze({
  AGDF_MCP_SDK_PACKAGE_SET_MISMATCH: "the installed MCP SDK packages differ from the lock shipped with this plugin",
  AGDF_MCP_SDK_DIGEST_MISMATCH: "the installed MCP SDK content differs from the version shipped with this plugin",
  AGDF_MCP_PACKAGE_ACQUISITION_FAILED: "npm could not install the locked MCP SDK (network, registry or integrity check)",
  AGDF_MCP_RUNTIME_UNOWNED: "the runtime directory exists but is not owned by AGDF",
  AGDF_MCP_PLUGIN_RUNTIME_INVALID: "the installed AGDF plugin is incomplete",
  AGDF_MCP_EXECUTABLE_CLAIM_CONTENDED: "the claim publication phase is still held by a verified live owner",
  AGDF_MCP_EXECUTABLE_CLAIM_LOCK_UNCONFIRMED: "the claim publication lock ownership cannot be confirmed",
  AGDF_MCP_EXECUTABLE_CLAIM_INVALID: "the executable claim failed its current runtime integrity check",
  AGDF_MCP_PLUGIN_RUNTIME_FAILED: "the AGDF MCP runtime could not be started",
  AGDF_MCP_PUBLICATION_DEADLINE_EXCEEDED: "the preparation and claim phases exhausted their shared publication deadline",
});

export function launcherFailureLine(code, phase) {
  if (!Object.hasOwn(LAUNCHER_FAILURES, code)) { code = 'AGDF_MCP_PLUGIN_RUNTIME_FAILED'; phase ??= 'preparation'; }
  const cause = LAUNCHER_FAILURES[code] ?? "the AGDF MCP runtime could not be prepared";
  const claimRecovery = {
    AGDF_MCP_EXECUTABLE_CLAIM_CONTENDED: 'Wait for the verified publication owner to finish, then deliberately refresh this connection; retain its live lock.',
    AGDF_MCP_EXECUTABLE_CLAIM_LOCK_UNCONFIRMED: 'Inspect publication lock ownership through the supported AGDF owner; do not remove an unconfirmed lock.',
    AGDF_MCP_PUBLICATION_DEADLINE_EXCEEDED: 'Prepare the runtime through the installed launcher --prepare before deliberately refreshing the affected connection.',
  };
  const recovery = claimRecovery[code] ?? (["AGDF_MCP_SDK_PACKAGE_SET_MISMATCH", "AGDF_MCP_SDK_DIGEST_MISMATCH", "AGDF_MCP_PACKAGE_ACQUISITION_FAILED"].includes(code)
    ? `Check your npm registry or mirror and restart; to accept an unverified SDK deliberately, set ${SDK_OVERRIDE_ENV}=1.`
    : code === "AGDF_MCP_RUNTIME_UNOWNED"
      ? "Move the directory away and restart."
      : "Reinstall the AGDF plugin and restart.");
  const observedPhase = ['preparation', 'facade'].includes(phase) ? `${phase} phase: ` : '';
  return `${code}: ${observedPhase}${cause}. ${recovery}`;
}

export async function launchPluginMcpServer({
  pluginRoot,
  argv = process.argv.slice(2),
  env = process.env,
  stdout = process.stdout,
  stderr = process.stderr,
  ensure = ensurePluginMcpRuntime,
  acquireClaim = acquireMcpExecutableClaim,
  execPath = process.execPath,
  startFacade = async ({ runtime, surface, cockpitDir, pluginRoot, env, publicationDeadline }) => {
    // The facade's Core resource binding reads the plugin root from the environment it is
    // loaded under; bind it on the injected environment before the dynamic import.
    env.AGDF_DISPATCH_PLUGIN_ROOT = pluginRoot;
    const { runMcpServer } = await import(pathToFileURL(join(runtime.packageRoot, "src/main.js")));
    return runMcpServer({ surface, cockpitDir, ownedPublication: runtime, ownedPublisher: createMcpGenerationPublisher(runtime, { publicationDeadline }) });
  },
} = {}) {
  const invocation = parseLauncherArguments(argv, env);
  if (!invocation) {
    stderr.write("AGDF_MCP_ARGUMENTS_INVALID\n");
    process.exitCode = 1;
    return null;
  }
  const { surface, dataRoot, cockpitDir, prepareOnly } = invocation;
  const publicationDeadline = performance.now() + CONCURRENT_PUBLICATION_WAIT_MS;
  let runtime;
  try {
    runtime = ensure({ pluginRoot, dataRoot, env, publicationDeadline });
  } catch (error) {
    const code = /^AGDF_[A-Z_]+/.exec(error?.message ?? "")?.[0] ?? 'AGDF_MCP_PLUGIN_RUNTIME_FAILED';
    stderr.write(`${launcherFailureLine(code, code === 'AGDF_MCP_PLUGIN_RUNTIME_FAILED' ? 'preparation' : undefined)}\n`);
    process.exitCode = 1;
    return null;
  }
  // Announced whenever the override is active, also when an existing runtime is reused under it.
  if (sdkOverrideActive(env) || runtime.sdkVerification === SDK_VERIFICATION.override) {
    stderr.write(`AGDF_MCP_SDK_UNVERIFIED_OVERRIDE: ${SDK_OVERRIDE_ENV}=1 is set, so the MCP SDK was not checked against the version shipped with this plugin. Unset it and restart to verify the runtime again.\n`);
  }
  if (prepareOnly) {
    stdout.write(`${JSON.stringify({ status: runtime.status, version: runtime.version, root: runtime.root, changed: runtime.changed })}\n`);
    return runtime;
  }
  // Retain the facade's immutable SDK/executable root before dynamic loading.
  // Its self-owned lifetime cannot be proven by PID polling after a host crash;
  // this claim conservatively remains protected. Direct generations have their
  // separate claims released only after an acknowledged, actual child exit.
  try { acquireClaim(runtime, { publicationDeadline }); }
  catch (error) {
    const code = ['AGDF_MCP_EXECUTABLE_CLAIM_CONTENDED', 'AGDF_MCP_EXECUTABLE_CLAIM_LOCK_UNCONFIRMED', 'AGDF_MCP_PUBLICATION_DEADLINE_EXCEEDED'].includes(error?.message)
      ? error.message : 'AGDF_MCP_EXECUTABLE_CLAIM_INVALID';
    stderr.write(`${launcherFailureLine(code)}\n`); process.exitCode = 1; return null;
  }
  try { return await startFacade({ runtime, surface, cockpitDir, pluginRoot, env, publicationDeadline }); }
  catch (error) {
    const code = Object.hasOwn(LAUNCHER_FAILURES, error?.message) ? error.message : 'AGDF_MCP_PLUGIN_RUNTIME_FAILED';
    stderr.write(`${launcherFailureLine(code, 'facade')}\n`); process.exitCode = 1; return null;
  }

}

export function claudePluginDataRoot({ claudeConfigDir, pluginId = "agdf@agdf" }) {
  // Claude Code names the directory after the plugin id with every character outside [A-Za-z0-9_-]
  // replaced by "-" (agdf@agdf -> agdf-agdf).
  return join(resolve(claudeConfigDir), "plugins", "data", pluginId.replace(/[^A-Za-z0-9_-]/g, "-"));
}

export const claudePluginMcpConstants = Object.freeze({ sdkPackageSpec: SDK_PACKAGE_SPEC, launcher: "mcp/agdf-mcp-launch.js" });

// Codex keeps the plugin-local MCP runtime in an AGDF-owned data root because it passes no plugin data
// directory; `codex plugin remove` cannot delete it. `dataRoot` is the launcher data root (--data);
// uninstall removes it only when it holds nothing but owned runtimes and abandoned stages under mcp/.
export function inspectPluginMcpDataRoot(dataRoot) {
  if (!existsSync(dataRoot)) return "absent";
  try {
    if (!lstatSync(dataRoot).isDirectory() || lstatSync(dataRoot).isSymbolicLink()) return "foreign";
    if (readdirSync(dataRoot).some((name) => name !== "mcp")) return "foreign";
    const mcpDataRoot = join(realpathSync(dataRoot), "mcp");
    if (!existsSync(mcpDataRoot)) return "owned";
    if (!lstatSync(mcpDataRoot).isDirectory() || lstatSync(mcpDataRoot).isSymbolicLink()) return "foreign";
    let protectedFiles = false;
    for (const name of readdirSync(mcpDataRoot)) {
      const path = join(mcpDataRoot, name);
      const stats = lstatSync(path);
      if (!stats.isDirectory() || stats.isSymbolicLink()) return "foreign";
      if (name !== 'generations') {
        if (!ownedRoot(path) && !name.startsWith('.stage-')) return 'foreign';
        protectedFiles = true; continue;
      }
      for (const key of readdirSync(path)) {
        const publication = join(path, key);
        if (!/^[0-9a-f]{64}$/u.test(key) || lstatSync(publication).isSymbolicLink() || !lstatSync(publication).isDirectory()) return 'foreign';
        for (const version of readdirSync(publication)) {
          const runtimeRoot = join(publication, version);
          if (!ownedRoot(runtimeRoot) || mcpRuntimeRetirementState(runtimeRoot) !== 'eligible') protectedFiles = true;
        }
      }
    }
    return protectedFiles ? 'protected' : "owned";
  } catch {
    return "foreign";
  }
}
