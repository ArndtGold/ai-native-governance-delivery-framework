import assert from 'node:assert/strict';
import { readFileSync, writeFileSync, unlinkSync } from 'node:fs';
import { join } from 'node:path';
import { pathToFileURL } from 'node:url';
import { compileMcpWorkerRuntime } from '../../../scripts/compile-mcp-worker-runtime.mjs';
import { digestMcpDispatcherPackage, inspectOwnedMcpRuntimeRoot, mcpDispatcherRuntimeEntries } from '../../core/lib/runtime/plugin-provenance.js';
import { createOwnedRuntimeFixture } from './owned-runtime.js';
import { pluginRoot } from '../../../scripts/support/plugin-mcp-fixture.js';
import { withStdioClient, unresolvedArguments } from './helpers.js';

const fixture = createOwnedRuntimeFixture({ pluginSourceRoot: pluginRoot, controlRuns: [] });
const entry = join(fixture.dispatcherRoot, 'lib/mcp-worker-runtime.js');
try {
  const bytes = readFileSync(entry);
  assert.match(bytes.toString(), /^\/\/ Generated by scripts\/compile-mcp-worker-runtime\.mjs;/u);
  assert.equal(bytes.includes(Buffer.from(fixture.dispatcherRoot)), false, 'the compiled image must be relocatable');
  const first = compileMcpWorkerRuntime(fixture.dispatcherRoot);
  assert.deepEqual(readFileSync(entry), bytes, 'regeneration after moving into node_modules preserves exact output');
  assert.equal(compileMcpWorkerRuntime(fixture.dispatcherRoot).digest, first.digest, 'repeated compilation is deterministic');
  assert.ok(first.original_module_urls.includes('runtime/core/lib/control-state/preview-render.js'));
  assert.ok(first.original_module_urls.includes('runtime/core/lib/control-inspect/doctor-observation.js'));

  const compiled = await import(pathToFileURL(entry).href);
  const full = await import(pathToFileURL(join(fixture.dispatcherRoot, 'lib/mcp-dispatch-runtime.js')).href);
  const worker = compiled.createMcpDispatchRuntime({ surface: 'codex' });
  const original = full.createMcpDispatchRuntime({ surface: 'codex' });
  try {
    assert.equal(worker.trustedContext.provenanceStatus, 'matched');
    assert.equal(worker.definition, original.definition, 'the actual dispatch descriptor remains the same module object');
    assert.deepEqual(worker.tools.map(t => t.definition), original.tools.map(t => t.definition));
    assert.equal(compiled.OWNED_LOCK_CHANNEL, full.OWNED_LOCK_CHANNEL);
    let parseError;
    const { presentation_language: _language, ...missingLanguage } = unresolvedArguments;
    try { worker.parse(missingLanguage); } catch (error) { parseError = error; }
    assert.ok(parseError);
    assert.deepEqual(worker.normalizeFailure(parseError, { phase: 'parse' }),
      { code: 'dispatch_input_invalid', dispatch: 'not_dispatched', field: 'presentation_language' });
    assert.deepEqual(worker.normalizeFailure(parseError, { phase: 'parse' }), original.normalizeFailure(parseError, { phase: 'parse' }),
      'original and compiled consumers share the real parser/error class boundary');
    writeFileSync(entry, Buffer.concat([bytes, Buffer.from('\n// deliberate owned-image drift\n')]));
    assert.throws(() => worker.verifyProducer(), /runtime_provenance_invalid/u, 'compiled bytes are freshly checked, never trusted through a prior observation');
  } finally { writeFileSync(entry, bytes); await worker.close(); await original.close(); }

  for (const name of ['agdf-defaults.json', 'agdf-defaults.schema.json']) {
    const path = join(fixture.dispatcherRoot, 'generated/plugins/agdf/meta', name), resource = readFileSync(path);
    unlinkSync(path);
    try { assert.equal(inspectOwnedMcpRuntimeRoot(fixture.root, '0.20.2').status, 'mismatch', 'a missing default resource cannot select a historical inventory'); }
    finally { writeFileSync(path, resource); }
  }

  unlinkSync(entry);
  try {
    assert.equal(inspectOwnedMcpRuntimeRoot(fixture.root, '0.20.2').status, 'mismatch', 'a missing declared worker cannot downgrade to the historical entry set');
  } finally { writeFileSync(entry, bytes); }

  const manifestPath = join(fixture.dispatcherRoot, 'package.json'), markerPath = join(fixture.root, '.agdf-mcp-owned.json');
  const manifestBytes = readFileSync(manifestPath), markerBytes = readFileSync(markerPath);
  try {
    const manifest = JSON.parse(manifestBytes); delete manifest.exports['./mcp-worker-runtime'];
    writeFileSync(manifestPath, JSON.stringify(manifest));
    assert.equal(mcpDispatcherRuntimeEntries(fixture.dispatcherRoot).includes('lib/mcp-worker-runtime.js'), false,
      'historical declarations preserve their pre-bundle wire entry set');
    const marker = JSON.parse(markerBytes); marker.dispatcher_digest = digestMcpDispatcherPackage(fixture.dispatcherRoot);
    writeFileSync(markerPath, JSON.stringify(marker));
    assert.equal(inspectOwnedMcpRuntimeRoot(fixture.root, '0.20.2').status, 'mismatch',
      'a new actual server import map rejects an older same-version dispatcher even with an internally consistent legacy digest');
  } finally { writeFileSync(manifestPath, manifestBytes); writeFileSync(markerPath, markerBytes); }

  writeFileSync(entry, '// foreign output\n');
  try {
    assert.throws(() => compileMcpWorkerRuntime(fixture.dispatcherRoot), /AGDF_WORKER_BUILD_FOREIGN_OUTPUT/u);
    assert.equal(readFileSync(entry, 'utf8'), '// foreign output\n');
  } finally { writeFileSync(entry, bytes); }

  for (const modern of [false, true]) await withStdioClient({ ...fixture, modern }, async client => {
    const result = await client.callTool({ name: 'agdf_dispatch', arguments: unresolvedArguments });
    assert.equal(result.isError, true, 'an unresolved target preserves the existing MCP error projection');
    assert.equal(result.structuredContent.outcome, 'target_unresolved');
    assert.equal(result.structuredContent.runtime.provenance_status, 'matched');
  });
  console.log('Compiled worker: relocation/determinism, shared descriptors/errors, fresh tamper/missing/interface refusal and both real protocols passed; synthetic only.');
} finally { fixture.dispose(); }
