import { spawnSync } from 'node:child_process';
import { createHash } from 'node:crypto';
import { readFileSync, realpathSync, writeFileSync } from 'node:fs';
import { dirname, isAbsolute, join, relative, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const script = fileURLToPath(import.meta.url);
const repository = resolve(dirname(script), '..');
const canonicalEntry = join(repository, 'packages/cli/lib/mcp-worker-runtime.js');
const entryName = 'lib/mcp-worker-runtime.js';
const header = '// Generated by scripts/compile-mcp-worker-runtime.mjs; do not edit.\n';
const sha256 = value => createHash('sha256').update(value).digest('hex');
const slash = value => value.replaceAll('\\', '/');
const inside = (root, path) => { const r = relative(root, path); return r === '' || !r.startsWith(`..${process.platform === 'win32' ? '\\' : '/'}`) && r !== '..' && !isAbsolute(r); };

// Generation and npm assembly remain synchronous APIs. Only the build child
// loads the locked compiler; no compiler is shipped or run by the MCP server.
export function compileMcpWorkerRuntime(packageRoot) {
  if (!isAbsolute(packageRoot) || realpathSync(packageRoot) !== packageRoot
    || packageRoot === dirname(dirname(canonicalEntry))) throw Error('AGDF_WORKER_BUILD_TARGET_INVALID');
  const result = spawnSync(process.execPath, [script, '--compile', packageRoot], {
    encoding: 'utf8', timeout: 30_000, maxBuffer: 2 * 1024 * 1024,
  });
  if (result.status !== 0) throw Error(`AGDF_WORKER_BUILD_FAILED: ${result.stderr || result.error?.message || result.signal || result.status}`);
  return JSON.parse(result.stdout);
}

async function buildWorker(packageRoot) {
  const { rolldown, VERSION } = await import('rolldown');
  const { parse } = await import('acorn');
  if (JSON.parse(readFileSync(join(repository, 'package.json'), 'utf8')).devDependencies?.rolldown !== VERSION)
    throw Error('AGDF_WORKER_BUILD_COMPILER_VERSION');
  const output = join(packageRoot, entryName);
  const source = readFileSync(canonicalEntry, 'utf8');
  const previous = readFileSync(output, 'utf8');
  if (previous !== source && !previous.startsWith(header)) throw Error('AGDF_WORKER_BUILD_FOREIGN_OUTPUT');
  const virtualEntry = '\0agdf:canonical-worker-entry';
  const shared = new Set(), observations = new Map(), rewritten = new Set();
  function observe(path) {
    const bytes = readFileSync(path), hash = sha256(bytes);
    if (observations.has(path) && observations.get(path) !== hash) throw Error('AGDF_WORKER_BUILD_SOURCE_CHANGED');
    observations.set(path, hash);
    return bytes.toString('utf8');
  }
  observations.set(canonicalEntry, sha256(source));
  const capture = {
    name: 'agdf-owned-build-inputs',
    load(id) {
      if (!isAbsolute(id)) return null;
      if (!inside(packageRoot, id) || !/\.[cm]?js$/u.test(id)) throw Error(`AGDF_WORKER_BUILD_UNOWNED_INPUT: ${id}`);
      return observe(id);
    },
  };
  // These modules contain the shared schemas, error classes, resource context
  // and file/read state. Keep their actual module identity shared with the
  // unbundled protocol; never introduce another contract or state singleton.
  const scan = await rolldown({ cwd: packageRoot, input: join(packageRoot, 'lib/mcp-protocol-runtime.js'), platform: 'node',
    plugins: [capture, { name: 'agdf-protocol-closure', moduleParsed(info) {
      if (isAbsolute(info.id)) shared.add(resolve(info.id));
    } }],
  });
  try { await scan.generate({ format: 'esm', codeSplitting: false }); } finally { await scan.close(); }
  const sourceIdentity = {
    name: 'agdf-original-module-identity',
    async resolveId(specifier, importer, options) {
      if (options.isEntry) return resolve(specifier) === output ? virtualEntry : null;
      if (!importer) return null;
      const actualImporter = importer === virtualEntry ? output : importer;
      const found = await this.resolve(specifier, actualImporter, { skipSelf: true });
      if (!found || !isAbsolute(found.id)) return found;
      if (!inside(packageRoot, found.id)) throw Error(`AGDF_WORKER_BUILD_UNOWNED_IMPORT: ${found.id}`);
      if (!shared.has(resolve(found.id))) return found;
      const corePath = slash(relative(join(packageRoot, 'runtime/core/lib'), found.id));
      return { id: !corePath.startsWith('../') ? `#agdf-core/${corePath}` : `./${slash(relative(dirname(output), found.id))}`, external: true };
    },
    load(id) { return id === virtualEntry ? source : null; },
    // Optional UI factories are not worker exports. Preserve their real lazy
    // import paths while tree-shaking the unused factories, including Copilot.
    resolveDynamicImport(specifier) {
      return typeof specifier === 'string' && specifier.startsWith('#agdf-core/') ? { id: specifier, external: true } : null;
    },
    transform(code, id) {
      if (id.startsWith('\0') || !code.includes('import.meta')) return null;
      const ast = parse(code, { ecmaVersion: 'latest', sourceType: 'module' });
      const edits = [], nodes = [ast];
      while (nodes.length) {
        const node = nodes.pop();
        if (!node || typeof node !== 'object') continue;
        if (node.type === 'MemberExpression' && node.object?.type === 'MetaProperty' && node.object.meta.name === 'import') {
          if (node.computed || node.property.name !== 'url') throw Error(`AGDF_WORKER_BUILD_UNSUPPORTED_META: ${id}`);
          edits.push([node.start, node.end]); continue;
        }
        for (const value of Object.values(node)) {
          if (Array.isArray(value)) nodes.push(...value);
          else if (value && typeof value === 'object') nodes.push(value);
        }
      }
      if (!edits.length) return null;
      const name = `__agdf_source_url_${sha256(slash(relative(packageRoot, id))).slice(0, 12)}`;
      if (code.includes(name)) throw Error('AGDF_WORKER_BUILD_IDENTIFIER_COLLISION');
      const corePath = slash(relative(join(packageRoot, 'runtime/core/lib'), id));
      const original = !corePath.startsWith('../') ? `import.meta.resolve(${JSON.stringify(`#agdf-core/${corePath}`)})`
        : `new URL(${JSON.stringify(`./${slash(relative(dirname(output), id))}`)},import.meta.url).href`;
      for (const [start, end] of edits.sort((a, b) => b[0] - a[0])) code = code.slice(0, start) + name + code.slice(end);
      rewritten.add(slash(relative(packageRoot, id)));
      return { code: `const ${name}=${original};\n${code}`, map: null };
    },
  };
  const bundle = await rolldown({ cwd: packageRoot, input: output, platform: 'node', plugins: [sourceIdentity, capture] });
  let generated;
  try { generated = await bundle.generate({ file: output, format: 'esm', codeSplitting: false,
    minify: { compress: false, mangle: false }, sourcemap: false }); } finally { await bundle.close(); }
  if (generated.output.length !== 1 || generated.output[0].type !== 'chunk') throw Error('AGDF_WORKER_BUILD_CHUNK_INVALID');
  const code = header + generated.output[0].code;
  if (code.includes(slash(repository)) || code.includes(slash(packageRoot))) throw Error('AGDF_WORKER_BUILD_ABSOLUTE_PATH');
  for (const [path, hash] of observations) if (sha256(readFileSync(path)) !== hash) throw Error('AGDF_WORKER_BUILD_SOURCE_CHANGED');
  if (readFileSync(output, 'utf8') !== previous) throw Error('AGDF_WORKER_BUILD_OUTPUT_CHANGED');
  writeFileSync(output, code, 'utf8');
  return { compiler: `rolldown@${VERSION}`, entry: entryName, bytes: Buffer.byteLength(code), digest: sha256(code),
    shared_modules: shared.size, original_module_urls: [...rewritten].sort() };
}

if (process.argv[1] && resolve(process.argv[1]) === script) {
  try {
    if (process.argv.length !== 4 || process.argv[2] !== '--compile') throw Error('AGDF_WORKER_BUILD_ARGUMENTS_INVALID');
    const root = process.argv[3];
    if (!isAbsolute(root) || realpathSync(root) !== root || root === dirname(dirname(canonicalEntry))) throw Error('AGDF_WORKER_BUILD_TARGET_INVALID');
    console.log(JSON.stringify(await buildWorker(root)));
  } catch (error) { process.stderr.write(`${error.stack ?? error}\n`); process.exitCode = 1; }
}
