import { chmodSync, lstatSync, mkdirSync, readFileSync, readdirSync, rmSync, statSync, writeFileSync } from "node:fs";
import { dirname, join, relative, resolve } from "node:path";
import { fileURLToPath } from "node:url";
import { CODEX_PLUGIN_MCP_FILE, renderCodexPluginMcpConfig, renderCopilotPluginMcpConfig } from "../packages/core/lib/runtime/plugin-provenance.js";

const scriptsRoot = dirname(fileURLToPath(import.meta.url));
const repoRoot = resolve(scriptsRoot, "..");
const serverSourceRoot = join(repoRoot, "packages", "mcp-server");
const SERVER_ENTRIES = Object.freeze(["package.json", "bin", "src", "README.md", "NOTICE"]);

// The Claude MCP registration is part of the runtime plugin, so `claude plugin uninstall` removes it.
// ${CLAUDE_PLUGIN_ROOT} and ${CLAUDE_PLUGIN_DATA} are expanded by Claude Code; the launcher reads the
// data root from the environment Claude Code passes to plugin MCP servers. The cockpit variant adds a
// separate read-only server bound to the project root Claude substitutes for ${CLAUDE_PROJECT_DIR}.
export function claudePluginMcpConfig({ cockpit = false } = {}) {
  const launcher = "${CLAUDE_PLUGIN_ROOT}/mcp/agdf-mcp-launch.js";
  return {
    mcpServers: {
      agdf: {
        type: "stdio",
        command: "node",
        args: [launcher],
      },
      ...(cockpit ? { "agdf-cockpit": { type: "stdio", command: "node", args: [launcher, "--cockpit-dir", "${CLAUDE_PROJECT_DIR}"] } } : {}),
    },
  };
}

// The runtime-only SDK closure of @agdf/mcp-server, taken from its reviewed lockfile: the server's own
// dependencies minus create-agdf, which the plugin ships itself.
export function runtimeSdkClosure(lock = JSON.parse(readFileSync(join(serverSourceRoot, "package-lock.json"), "utf8"))) {
  const roots = Object.keys(lock.packages?.[""]?.dependencies ?? {}).filter((name) => name !== "create-agdf");
  const closure = new Map();
  const pending = [...roots];
  while (pending.length) {
    const name = pending.shift();
    if (closure.has(name)) continue;
    const entry = lock.packages[`node_modules/${name}`];
    if (!entry || entry.dev || !entry.version || !entry.resolved || !entry.integrity) {
      throw new Error(`Plugin MCP SDK lock entry invalid: ${name}`);
    }
    closure.set(name, entry);
    pending.push(...Object.keys(entry.dependencies ?? {}));
  }
  const dependencies = Object.fromEntries(roots.map((name) => [name, lock.packages[""].dependencies[name]]));
  return { dependencies, entries: [...closure].sort(([left], [right]) => (left < right ? -1 : 1)) };
}

export const SDK_DIGEST_SOURCE = join(serverSourceRoot, "sdk-runtime-digest.json");

// mcp/sdk/: package.json and package-lock.json for `npm ci`, and the expected digest of the installed tree.
export function renderPluginMcpSdkBundle({ digestSource = JSON.parse(readFileSync(SDK_DIGEST_SOURCE, "utf8")) } = {}) {
  const { dependencies, entries } = runtimeSdkClosure();
  const name = "agdf-plugin-mcp-sdk";
  const packages = entries.map(([entryName, entry]) => ({ name: entryName, version: entry.version, integrity: entry.integrity }));
  if (digestSource.schema_version !== 1 || typeof digestSource.sdk_digest !== "string"
      || JSON.stringify(digestSource.packages) !== JSON.stringify(packages)) {
    throw new Error("packages/mcp-server/sdk-runtime-digest.json is stale; run npm run mcp:sdk-digest");
  }
  const json = (value) => `${JSON.stringify(value, null, 2)}\n`;
  return {
    "package.json": json({ name, private: true, dependencies }),
    "package-lock.json": json({
      name,
      lockfileVersion: 3,
      requires: true,
      packages: {
        "": { name, dependencies },
        ...Object.fromEntries(entries.map(([entryName, entry]) => [`node_modules/${entryName}`, entry])),
      },
    }),
    "expected-sdk.json": json({ schema_version: 1, sdk_digest: digestSource.sdk_digest, packages }),
  };
}

const LAUNCHER = `#!/usr/bin/env node

// Generated by scripts/sync-plugin-mcp.js; do not edit.
import { fileURLToPath } from "node:url";
import { launchPluginMcpServer } from "../runtime/create-agdf/lib/mcp-lifecycle/plugin-runtime.js";

await launchPluginMcpServer({ pluginRoot: fileURLToPath(new URL("../", import.meta.url)) });
`;

function copyText(source, destination, expected, root) {
  const stats = statSync(source);
  if (stats.isDirectory()) {
    for (const entry of readdirSync(source)) copyText(join(source, entry), join(destination, entry), expected, root);
    return;
  }
  mkdirSync(dirname(destination), { recursive: true });
  writeFileSync(destination, readFileSync(source, "utf8").replaceAll("\r\n", "\n"), "utf8");
  chmodSync(destination, stats.mode);
  expected.add(relative(root, destination).replaceAll("\\", "/"));
}

// Writes the runtime plugin's mcp/ directory: the shared launcher and server copy plus one declaration per
// host whose plugin starts the server itself (Claude Code, and Codex as an installer-completed template).
// `cockpitUi` (a verified build from cockpit-ui-build.mjs) selects the Claude cockpit variant.
export function syncPluginMcp({ pluginRoot, profile = "shared", cockpitUi } = {}) {
  if (!pluginRoot || resolve(pluginRoot) !== pluginRoot) throw new Error("Plugin MCP sync requires an absolute pluginRoot.");
  if (!["shared", "copilot"].includes(profile)) throw new Error("Plugin MCP sync requires a supported profile.");
  if (cockpitUi && profile !== "shared") throw new Error("Plugin MCP cockpit variant requires the shared profile.");
  const mcpRoot = join(pluginRoot, "mcp");
  mkdirSync(mcpRoot, { recursive: true });
  const expected = new Set(["agdf-mcp-launch.js"]);
  if (profile === "shared") {
    writeFileSync(join(mcpRoot, "claude.mcp.json"), `${JSON.stringify(claudePluginMcpConfig({ cockpit: Boolean(cockpitUi) }), null, 2)}\n`, "utf8");
    expected.add("claude.mcp.json");
  }
  writeFileSync(join(mcpRoot, "agdf-mcp-launch.js"), LAUNCHER, "utf8");
  mkdirSync(join(mcpRoot, "sdk"), { recursive: true });
  for (const [name, content] of Object.entries(renderPluginMcpSdkBundle())) {
    writeFileSync(join(mcpRoot, "sdk", name), content, "utf8");
    expected.add(`sdk/${name}`);
  }
  writeFileSync(join(pluginRoot, CODEX_PLUGIN_MCP_FILE),
    profile === "shared" ? renderCodexPluginMcpConfig() : renderCopilotPluginMcpConfig(), "utf8");
  for (const entry of SERVER_ENTRIES) {
    copyText(join(serverSourceRoot, entry), join(mcpRoot, "server", entry), expected, mcpRoot);
  }
  if (cockpitUi) {
    // Exact verified bytes; cockpit-resource.js reads them from server/ui/ relative to server/src/.
    mkdirSync(join(mcpRoot, "server", "ui"), { recursive: true });
    for (const [name, bytes] of Object.entries(cockpitUi.files)) {
      writeFileSync(join(mcpRoot, "server", "ui", name), bytes);
      expected.add(`server/ui/${name}`);
    }
  }
  const pruneRoot = (directory) => {
    for (const name of readdirSync(directory)) {
      const path = join(directory, name);
      const stats = lstatSync(path);
      if (stats.isDirectory() && !stats.isSymbolicLink()) {
        pruneRoot(path);
        if (readdirSync(path).length === 0) rmSync(path, { recursive: true, force: true });
      } else if (!expected.has(relative(mcpRoot, path).replaceAll("\\", "/"))) {
        rmSync(path, { force: true });
      }
    }
  };
  pruneRoot(mcpRoot);
  return [...expected].sort().map((path) => `mcp/${path}`);
}
